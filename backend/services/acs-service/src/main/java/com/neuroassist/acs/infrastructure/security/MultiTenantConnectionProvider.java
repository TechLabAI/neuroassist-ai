package com.neuroassist.acs.infrastructure.security;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import javax.sql.DataSource;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.hibernate.engine.jdbc.connections.spi.AbstractDataSourceBasedMultiTenantConnectionProviderImpl;
import org.springframework.stereotype.Component;

/**
 * Hibernate hook that switches the Postgres {@code search_path} per connection based on {@link
 * TenantContextHolder}. Realises the schema-per-tenant strategy declared in multi-tenancy.arch.json
 * (D-063); generated by D-071.
 *
 * <p>Single shared HikariCP DataSource is used — only the search_path varies per request.
 * Connections are returned to the pool with their search_path reset to the global catalogue, so a
 * connection leak cannot leak data between tenants.
 */
@Slf4j
@Component
@RequiredArgsConstructor
public class MultiTenantConnectionProvider
        extends AbstractDataSourceBasedMultiTenantConnectionProviderImpl {

    private static final String GLOBAL_SCHEMA = "neuroassist_global";

    private final DataSource dataSource;

    @Override
    protected DataSource selectAnyDataSource() {
        return dataSource;
    }

    @Override
    protected DataSource selectDataSource(Object tenantIdentifier) {
        return dataSource;
    }

    @Override
    public Connection getConnection(Object tenantIdentifier) throws SQLException {
        Connection connection = super.getConnection(tenantIdentifier);
        String tenant = tenantIdentifier == null ? null : tenantIdentifier.toString();
        try (Statement st = connection.createStatement()) {
            if (tenant != null && !tenant.isBlank() && !GLOBAL_SCHEMA.equals(tenant)) {
                st.execute("SET search_path TO \"" + tenant + "\", " + GLOBAL_SCHEMA + ", public");
            } else {
                st.execute("SET search_path TO " + GLOBAL_SCHEMA + ", public");
            }
        }
        return connection;
    }

    @Override
    public void releaseConnection(Object tenantIdentifier, Connection connection)
            throws SQLException {
        try (Statement st = connection.createStatement()) {
            st.execute("SET search_path TO " + GLOBAL_SCHEMA + ", public");
        } catch (SQLException e) {
            log.warn(
                    "Failed to reset search_path for tenant {} on release: {}",
                    tenantIdentifier,
                    e.getMessage());
        }
        super.releaseConnection(tenantIdentifier, connection);
    }
}
