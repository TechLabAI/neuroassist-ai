    private void postHeartbeat(Long runningProfileVersion) {
        String body;
        if (runningProfileVersion == null) {
            body = "{\"agentVersion\":\"1.0\",\"runningProfileVersion\":null}";
        } else {
            body = "{\"agentVersion\":\"1.0\",\"runningProfileVersion\":" + runningProfileVersion + "}";
        }
        HttpHeaders headers = new HttpHeaders();
        headers.setBearerAuth(testContext.getDeviceToken());
        headers.setContentType(MediaType.APPLICATION_JSON);
        ResponseEntity<String> response =
                restTemplate.postForEntity(
                        "/api/v1/edge/heartbeat",
                        new HttpEntity<>(body, headers),
                        String.class);
        testContext.setLastResponse(response);
    }

    private ResponseEntity<String> getWithServiceToken(String url, String serviceToken) {
        HttpHeaders headers = new HttpHeaders();
        headers.setBearerAuth(serviceToken);
        return restTemplate.exchange(url, HttpMethod.GET, new HttpEntity<>(headers), String.class);
    }

