package com.neuroassist.pac.application.service;

import com.neuroassist.pac.application.port.in.ComandoAuthoringUseCase;
import com.neuroassist.pac.application.port.out.ComandoRepositoryPort;
import com.neuroassist.pac.application.port.out.PacienteRepositoryPort;
import com.neuroassist.pac.domain.model.Comando;
import com.neuroassist.pac.domain.model.EstadoComando;
import com.neuroassist.pac.domain.model.Sensibilidade;
import com.neuroassist.pac.domain.model.Urgencia;
import com.neuroassist.pac.infrastructure.security.TenantContextHolder;
import com.neuroassist.pac.shared.error.CodedException;
import java.time.Instant;
import java.util.List;
import java.util.UUID;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * PAC-012/PAC-013 — Comando authoring use cases: createDraft and editDraft.
 *
 * <p>Hexagonal rules enforced:
 *
 * <ul>
 *   <li>RULE-03: {@code @Transactional} ONLY here — never in controllers or adapters.
 *   <li>RULE-07: {@code TenantContextHolder.require()} is the first call in every public method
 *       that touches empresa-scoped data.
 *   <li>RULE-01/02: domain Comando has no Spring/JPA imports.
 *   <li>RULE-04/05: no infrastructure.* dependency — only ports are injected.
 * </ul>
 *
 * <p>Guards for createDraft (SPEC-02 §5.1):
 *
 * <ol>
 *   <li>pacienteId belongs to current tenant.
 *   <li>rotulo / necessidade non-blank (Bean Validation on DTO — fires before service call).
 *   <li>tempoMinGestoMs {@code > 0} and {@code <= tempoMaxGestoMs}.
 *   <li>If composite: primitivoSecundarioId {@code != primitivoPrincipalId}.
 *   <li>No active duplicate mapping — advisory pre-flight in {@link ComandoRepositoryPort#save}
 *       plus DB partial index {@code ux_comando_active_mapping} as authoritative guard.
 * </ol>
 */
@Slf4j
@Service
@RequiredArgsConstructor
public class ComandoAuthoringService implements ComandoAuthoringUseCase {

    private final ComandoRepositoryPort comandoRepository;
    private final PacienteRepositoryPort pacienteRepository;

    // -------------------------------------------------------------------------
    // PAC-012: createDraft
    // -------------------------------------------------------------------------

    @Override
    @Transactional
    public Comando createDraft(
            UUID pacienteId,
            String rotulo,
            String necessidade,
            UUID primitivoPrincipalId,
            UUID primitivoSecundarioId,
            Sensibilidade sensibilidade,
            int tempoMinGestoMs,
            int tempoMaxGestoMs,
            Urgencia urgencia) {

        String tenantId = TenantContextHolder.require(); // RULE-07

        // Guard 1: pacienteId must belong to current tenant
        pacienteRepository
                .findByIdAndTenantId(pacienteId, tenantId)
                .orElseThrow(
                        () ->
                                new CodedException(
                                        "not_found.paciente", "Paciente not found: " + pacienteId));

        // Guard 3: timing (Guard 2 is @NotBlank via Bean Validation on the request DTO)
        validateTiming(tempoMinGestoMs, tempoMaxGestoMs);

        // Guard 4: composite gesture — principal and secondary must differ
        validateCompositePrimitives(primitivoPrincipalId, primitivoSecundarioId);

        // Guard 5: duplicate active mapping is enforced by ComandoRepositoryPort.save()
        // (advisory pre-flight + DB partial index ux_comando_active_mapping as safety net)

        Instant now = Instant.now();
        Comando draft =
                new Comando(
                        null, // id generated by JPA / DB sequence
                        pacienteId,
                        rotulo,
                        necessidade,
                        primitivoPrincipalId,
                        primitivoSecundarioId,
                        sensibilidade,
                        tempoMinGestoMs,
                        tempoMaxGestoMs,
                        urgencia,
                        EstadoComando.drafted,
                        0, // calibracaoVersao = 0 (SPEC-02 §5.1)
                        0, // rowVersion = 0
                        now,
                        now);

        Comando saved = comandoRepository.save(draft);
        log.info(
                "Comando draft created id={} pacienteId={} tenant={}",
                saved.id(),
                pacienteId,
                tenantId);
        return saved;
    }

    // -------------------------------------------------------------------------
    // PAC-013: editDraft
    // -------------------------------------------------------------------------

    @Override
    @Transactional
    public Comando editDraft(
            UUID pacienteId,
            UUID comandoId,
            int expectedRowVersion,
            String rotulo,
            String necessidade,
            UUID primitivoPrincipalId,
            UUID primitivoSecundarioId,
            Sensibilidade sensibilidade,
            int tempoMinGestoMs,
            int tempoMaxGestoMs,
            Urgencia urgencia) {

        String tenantId = TenantContextHolder.require(); // RULE-07

        // Guard 1: pacienteId must belong to current tenant
        pacienteRepository
                .findByIdAndTenantId(pacienteId, tenantId)
                .orElseThrow(
                        () ->
                                new CodedException(
                                        "not_found.paciente", "Paciente not found: " + pacienteId));

        // Load existing Comando scoped to this Paciente (cross-patient access defense)
        Comando existing =
                comandoRepository
                        .findByIdAndPacienteId(comandoId, pacienteId)
                        .orElseThrow(
                                () ->
                                        new CodedException(
                                                "not_found.comando",
                                                "Comando not found: " + comandoId));

        // Guard: only drafted Comandos can be edited — any other state → 409
        if (existing.estado() != EstadoComando.drafted) {
            log.warn(
                    "editDraft rejected for comando={} estado={} — only drafted is editable",
                    comandoId,
                    existing.estado());
            throw new CodedException(
                    "pac.comando.invalid-lifecycle-transition",
                    "Cannot edit a comando in state '"
                            + existing.estado()
                            + "'. Only drafted commands can be edited.");
        }

        // Optimistic lock: rowVersion (If-Match header) must match current version
        if (existing.rowVersion() != expectedRowVersion) {
            log.warn(
                    "editDraft ETag stale comando={} expected={} current={}",
                    comandoId,
                    expectedRowVersion,
                    existing.rowVersion());
            throw new CodedException(
                    "conflict-precondition",
                    "ETag stale — expected rowVersion "
                            + expectedRowVersion
                            + " but current is "
                            + existing.rowVersion());
        }

        // Guard: timing
        validateTiming(tempoMinGestoMs, tempoMaxGestoMs);

        // Guard: composite gesture
        validateCompositePrimitives(primitivoPrincipalId, primitivoSecundarioId);

        Instant now = Instant.now();
        Comando updated =
                new Comando(
                        existing.id(),
                        pacienteId,
                        rotulo,
                        necessidade,
                        primitivoPrincipalId,
                        primitivoSecundarioId,
                        sensibilidade,
                        tempoMinGestoMs,
                        tempoMaxGestoMs,
                        urgencia,
                        EstadoComando.drafted, // estado remains drafted
                        existing.calibracaoVersao(), // calibracaoVersao unchanged on edit
                        existing.rowVersion() + 1, // bump rowVersion for optimistic lock
                        existing.createdAt(),
                        now);

        Comando saved = comandoRepository.save(updated);
        log.info(
                "Comando draft edited id={} pacienteId={} tenant={} newVersion={}",
                comandoId,
                pacienteId,
                tenantId,
                saved.rowVersion());
        return saved;
    }

    // -------------------------------------------------------------------------
    // Read operations
    // -------------------------------------------------------------------------

    @Override
    @Transactional(readOnly = true)
    public List<Comando> listByPaciente(UUID pacienteId) {
        String tenantId = TenantContextHolder.require(); // RULE-07

        pacienteRepository
                .findByIdAndTenantId(pacienteId, tenantId)
                .orElseThrow(
                        () ->
                                new CodedException(
                                        "not_found.paciente", "Paciente not found: " + pacienteId));

        return comandoRepository.findActiveByPacienteId(pacienteId);
    }

    @Override
    @Transactional(readOnly = true)
    public Comando findByIdAndPacienteId(UUID pacienteId, UUID comandoId) {
        String tenantId = TenantContextHolder.require(); // RULE-07

        pacienteRepository
                .findByIdAndTenantId(pacienteId, tenantId)
                .orElseThrow(
                        () ->
                                new CodedException(
                                        "not_found.paciente", "Paciente not found: " + pacienteId));

        return comandoRepository
                .findByIdAndPacienteId(comandoId, pacienteId)
                .orElseThrow(
                        () ->
                                new CodedException(
                                        "not_found.comando", "Comando not found: " + comandoId));
    }

    // -------------------------------------------------------------------------
    // Private validation helpers
    // -------------------------------------------------------------------------

    /**
     * Guard 3 — timing: tempoMinGestoMs must be > 0 and <= tempoMaxGestoMs. Bean Validation on DTO
     * enforces @Min(1) for each individually; this guard enforces the relational constraint between
     * the two.
     */
    private void validateTiming(int tempoMinGestoMs, int tempoMaxGestoMs) {
        if (tempoMinGestoMs > tempoMaxGestoMs) {
            throw new CodedException(
                    "pac.timing.invalid",
                    "tempoMinGestoMs ("
                            + tempoMinGestoMs
                            + ") must be <= tempoMaxGestoMs ("
                            + tempoMaxGestoMs
                            + ")");
        }
    }

    /**
     * Guard 4 — composite gesture: primitivoSecundarioId must differ from primitivoPrincipalId when
     * present (SPEC-02 §5.1 guard 4).
     */
    private void validateCompositePrimitives(
            UUID primitivoPrincipalId, UUID primitivoSecundarioId) {
        if (primitivoSecundarioId != null && primitivoSecundarioId.equals(primitivoPrincipalId)) {
            throw new CodedException(
                    "pac.comando.same-primitive",
                    "primitivoPrincipalId and primitivoSecundarioId must differ; got "
                            + primitivoPrincipalId
                            + " for both");
        }
    }
}
