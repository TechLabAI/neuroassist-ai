    private ProblemDetailFactory() {}

    /**
     * Build a ProblemDetail for the given error code. Unknown codes are mapped to the
     * internal_error fallback so the response is still a valid ProblemDetail; the unknown code is
     * logged in `error.code` for the FE to surface (or for ops to investigate as a missing entry).
     */
    public static ProblemDetail forCode(
            String code, Throwable ex, HttpServletRequest req, Map<String, Object> context) {
        ErrorMetadata meta =
                code == null
                        ? INTERNAL_FALLBACK
                        : CODE_METADATA.getOrDefault(code, INTERNAL_FALLBACK);
        ProblemDetail pd = ProblemDetail.forStatus(HttpStatus.valueOf(meta.httpStatus()));
        pd.setTitle(meta.title());
        pd.setDetail(
                ex != null && ex.getMessage() != null && !ex.getMessage().equals(code)
                        ? ex.getMessage()
                        : meta.title());
        String resolvedCode = code == null ? "internal_error" : code;
        String typeUri = TYPE_OVERRIDES.getOrDefault(
                resolvedCode, TYPE_URI_TEMPLATE.replace("{code}", resolvedCode));
        pd.setType(URI.create(typeUri));
        if (req != null) {
            pd.setInstance(URI.create(req.getRequestURI()));
        }
        // Extension fields under top-level keys (Spring ProblemDetail flattens
        // them via setProperty; FE convention groups them under "error").
        pd.setProperty(
                "error",
                Map.of(
                        "code", code == null ? "internal_error.unhandled" : code,
                        "category", meta.category(),
                        "correlationId", Objects.requireNonNullElse(MDC.get("correlationId"), ""),
                        "timestamp", OffsetDateTime.now().toString(),
                        "context", context == null ? Map.of() : context));
        return pd;
    }

    public static ProblemDetail forCode(String code, Throwable ex, HttpServletRequest req) {
        return forCode(code, ex, req, Map.of());
    }

    /** Convenience for tests / programmatic use. */
